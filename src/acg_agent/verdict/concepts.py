"""概念 → 标签名的同义词表（手工维护）。

规则：
- 精确匹配标签名，不做子串匹配。“逆后宫”（女主角被多个男性追求）和“后宫”是不同概念，
  子串匹配会把 34 部带“逆后宫”标签的动画误判成后宫番。
- 只收录在数据里真实出现过的写法（2026-10-20 快照核对过）。
- 表里没有的概念，只按概念本身精确匹配一个标签名。
"""

TAG_SYNONYMS: dict[str, tuple[str, ...]] = {
    "后宫": ("后宫", "後宮"),
    "百合": ("百合", "百合向"),
    "治愈": ("治愈", "治愈系", "治癒"),
    "致郁": ("致郁", "致郁系"),
    "恋爱": ("恋爱", "戀愛"),
    "校园": ("校园", "校園"),
    "战斗": ("战斗", "戰鬥"),
    "热血": ("热血", "熱血"),
    "猎奇": ("猎奇", "獵奇"),
    "机战": ("机战", "机甲"),
    "卖肉": ("卖肉", "賣肉", "福利"),
}


def tag_names(concept: str) -> tuple[str, ...]:
    concept = concept.strip()
    return TAG_SYNONYMS.get(concept, (concept,))
